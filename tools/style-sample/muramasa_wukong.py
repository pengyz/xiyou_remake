TEAL_D = (30, 74, 72)
DARK_BR = (58, 36, 24)        # 靴/发暗棕
SKIN = (238, 210, 168)        # 手

img = Image.new("RGBA", (W * S, H * S), (0, 0, 0, 0))
d = ImageDraw.Draw(img)


def poly(pts, fill, outline=None, wline=6):
    sp = [(x * S, y * S) for x, y in pts]
    d.polygon(sp, fill=fill)
    if outline:
        # 变宽笔触：粗描一层再内嵌细描，近似毛笔墨线
        d.line(sp + [sp[0]], fill=outline, width=wline * S // 2, joint="curve")


def ell(cx, cy, rx, ry, fill, outline=None, wline=6):
    box = [(cx - rx) * S, (cy - ry) * S, (cx + rx) * S, (cy + ry) * S]
    d.ellipse(box, fill=fill)
    if outline:
        d.ellipse(box, outline=outline, width=wline * S // 2)


def brush(pts, color, w0=8, w1=3):
    """变宽曲线（雉鸡翎/衣纹的笔触感）：分段由粗到细。"""
    n = len(pts)
    for i in range(n - 1):
        t = i / max(n - 2, 1)
        w = int((w0 + (w1 - w0) * t) * S / 2)
        d.line([(pts[i][0] * S, pts[i][1] * S), (pts[i + 1][0] * S, pts[i + 1][1] * S)],
               fill=color, width=max(w, 1))


